"""Опубликовать архив data/olympiads в docs/practice/olympiads.

Исходники остаются в data/, ссылки README.md становятся ссылками index.md.
--check сверяет страницы без записи. Удаление файлов не производится.
"""
import argparse
import os
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/olympiads"
DEST = ROOT / "docs/practice/olympiads"
MARK = "<!-- Generated by scripts/sync_olympiad_archive.py; edit data/olympiads instead. -->"
LINK = re.compile(r"(\[[^\]]*\]\()([^)]+)(\))")
PROBLEM = re.compile(r"https://codeforces\.com/(?:gym|contest)/(\d+)/problem/([A-Za-z0-9]+)")
ORDER = ["vsosh-final", "vsosh-region", "open-olympiad", "vysshaya-proba", "innopolis-open", "vorgcup"]


def target_for(source):
    relative = source.relative_to(SOURCE)
    if relative.name == "README.md":
        relative = relative.with_name("index.md")
    return DEST / relative


def relative_link(target, page):
    return Path(os.path.relpath(target, page.parent)).as_posix()


def transform(source, mapping):
    text = source.read_text(encoding="utf-8")
    target = mapping[source]

    def rewrite(match):
        raw = match[2]
        url = urlsplit(raw)
        if url.scheme or url.netloc or not url.path:
            return match[0]
        referenced = (source.parent / url.path).resolve()
        if referenced not in mapping:
            raise ValueError(f"Unmapped local link: {source.relative_to(ROOT)} -> {raw}")
        href = relative_link(mapping[referenced], target)
        if url.fragment:
            href += "#" + url.fragment
        return match[1] + href + match[3]

    text = LINK.sub(rewrite, text)
    if source.name != "README.md":
        back = "[← Задачи этого сезона](index.md)"
    elif len(source.relative_to(SOURCE).parts) == 3:
        back = "[← Все сезоны олимпиады](../index.md)"
    else:
        back = "[← Все олимпиады](../index.md)"
    if source.name != "README.md" and "олимпиадником не проверен" in text:
        title, rest = text.split("\n", 1)
        text = title + '\n\n!!! warning "Разбор ждёт человеческой вычитки"\n    Это черновик на основе указанных источников. Статус проверки сохранён из материалов команды.\n' + rest
    return MARK + "\n\n" + back + "\n\n" + text.rstrip() + "\n"


def landing(files):
    seasons = [p for p in files if p.name == "README.md" and len(p.relative_to(SOURCE).parts) == 3]
    editorials = [p for p in files if p.name != "README.md"]
    problems = {m for p in seasons for m in PROBLEM.findall(p.read_text(encoding="utf-8"))}
    lines = ["---", "title: Архив олимпиад", "---", "", MARK, "", "[← Практика по темам](../index.md)", "",
             "# Архив олимпиад", "", "Олимпиада → сезон → условия, задачи и разборы. Выбери соревнование или начни с подготовленных разборов.",
             "{: .ob-lead }", "", f"**Олимпиад: {len(ORDER)} · сезонов: {len(seasons)} · задач на Codeforces: {len(problems)}.**", "",
             f'!!! info "Что уже есть"\n    Здесь собраны ссылки на найденные официальные материалы. На сайте размещено {len(editorials)} черновиков разборов; их статус указан на страницах. Остальные ссылки не означают наличие готового разбора или проверку доступности внешнего сайта.', "",
             "[Открыть восемь разборов финала ВсОШ 2025–2026](vsosh-final/2025-2026/index.md){ .ob-btn .ob-btn--primary }", "",
             '<div class="grid" markdown>', ""]
    for slug in ORDER:
        source = SOURCE / slug / "README.md"
        title = source.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ")
        group = [p for p in seasons if p.relative_to(SOURCE).parts[0] == slug]
        count = len({m for p in group for m in PROBLEM.findall(p.read_text(encoding="utf-8"))})
        lines.extend(['<div class="ob-card" markdown>', "", f"### [{title}]({slug}/index.md)", "",
                      f"Сезонов: {len(group)} · задач Codeforces: {count}", "{: .ob-note }", "", "</div>", ""])
    lines.extend(["</div>", "", "Условия и официальные разборы открываются на сайтах организаторов. Архив содержит найденные материалы; полнота всех исторических сезонов не подтверждена.", ""])
    return "\n".join(lines)


def build_pages():
    files = sorted(p.resolve() for p in SOURCE.rglob("*.md"))
    mapping = {p: target_for(p) for p in files}
    root = (SOURCE / "README.md").resolve()
    pages = {target: transform(source, mapping) for source, target in mapping.items() if source != root}
    pages[DEST / "index.md"] = landing(files)
    return pages


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    pages = build_pages()
    changed = [path for path, text in pages.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    stale = [p for p in DEST.rglob("*.md") if p not in pages and MARK in p.read_text(encoding="utf-8")]
    if args.check:
        for path in changed + stale:
            print("OUTDATED:", path.relative_to(ROOT))
        print(f"{'RED' if changed or stale else 'GREEN'}: {len(pages)} archive pages")
        return int(bool(changed or stale))
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(pages[path], encoding="utf-8")
    print(f"Archive: {len(pages)} pages; updated {len(changed)}; obsolete generated pages {len(stale)}")
    return int(bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
